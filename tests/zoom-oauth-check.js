// Kiểm tra OAuth bằng mạng Zoom giả lập; tuyệt đối không gọi tài khoản Zoom thật.
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const express = require('express');
const crypto = require('node:crypto');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'englive-zoom-auth-'));
process.env.DATA_DIR = dir;
const store = require('../db');
const { createRouter, hostSetup } = require('../zoom');
const originalFetch = global.fetch;
let server, calls = [], tokenRequests = [], sessionValid = true, failureStage = '';
async function main() {
  const teacher = store.data.users.find(u => u.role === 'teacher'), student = store.data.users.find(u => u.role === 'student');
  store.data.settings.video = { zoom: { clientId: 'mock-client', clientSecret: 'mock-secret', publicClientId: 'mock-public', redirectUri: 'http://127.0.0.1:3000/api/zoom/oauth/callback' } };
  const c = { id: 'zoom-auth-class', teacherId: teacher.id, studentIds: [student.id] };
  const live = { video: { provider: 'zoom', hostMode: 'sdk', hostEmail: 'host@example.com', meetingNumber: '1234567890', password: 'p' }, teacherSocket: 'teacher-socket', viewers: new Map([['student-socket', { userId: student.id }]]) };
  const users = { teacher: teacher, student: student };
  assert.equal(hostSetup(teacher, live.video).code, 'connect');
  const sockets = new Map(Object.entries(users).map(([token, user]) => [token + '-socket', { connected: true, data: { token, user, classId: c.id } }]));
  global.fetch = async (url, opts = {}) => {
    // user:read:zak authorizes /users/me/zak; the generic /token API needs different scopes.
    assert.ok(['https://zoom.us/oauth/token', 'https://api.zoom.us/v2/users/me', 'https://api.zoom.us/v2/users/me/zak'].includes(String(url)), 'chỉ gọi API đúng với quyền profile và ZAK đã hướng dẫn');
    calls.push(String(url));
    const stage = String(url).includes('/oauth/token') ? 'token' : String(url).endsWith('/users/me/zak') ? 'zak' : 'profile';
    if (failureStage === stage) return Response.json({ code: 4711, reason: 'Missing scope user:read:zak; client_secret=mock-secret access_token=mock-access refresh_token=mock-refresh' }, { status: 401 });
    if (failureStage === 'network') throw Object.assign(new Error('fetch failed'), { cause: { code: 'ECONNRESET' } });
    if (String(url).includes('/oauth/token')) { tokenRequests.push({ fields: new URLSearchParams(opts.body), authorization: opts.headers.Authorization }); return Response.json({ access_token: 'mock-access', refresh_token: 'mock-refresh', expires_in: 3600 }); }
    if (String(url).endsWith('/users/me/zak')) return Response.json({ token: 'mock-zak' });
    return Response.json({ id: 'mock-host-id', email: 'host@example.com' });
  };
  const app = express(); app.use(express.json());
  const auth = role => (req, res, next) => { const token = (req.headers.authorization || '').replace('Bearer ', ''), user = users[token]; if (!user) return res.sendStatus(401); if (role && role !== user.role) return res.sendStatus(403); req.user = user; req.token = token; next(); };
  app.use(createRouter({ auth, userFromToken: token => sessionValid ? users[token] : null, io: { sockets: { sockets } }, lk: { enabled: false }, lives: new Map([[c.id, live]]), findClass: id => id === c.id ? c : null, canAccess: (u, cls) => !!cls && (u.id === teacher.id || cls.studentIds.includes(u.id)) }));
  await new Promise(r => { server = app.listen(0, '127.0.0.1', r); });
  const request = async (url, token = 'teacher', body, origin) => {
    const response = await originalFetch('http://127.0.0.1:' + server.address().port + url, { method: body ? 'POST' : 'GET', headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json', ...(origin ? { Origin: origin } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}), redirect: 'manual' });
    return { status: response.status, location: response.headers.get('location'), body: await response.json().catch(() => ({})) };
  };
  const start = await request('/api/zoom/connect', 'teacher', {});
  const state = new URL(start.body.url).searchParams.get('state');
  const params = new URL(start.body.url).searchParams;
  assert.equal(params.get('client_id'), 'mock-public');
  assert.equal(params.get('code_challenge_method'), 'S256');
  assert.ok(!params.has('code_verifier'));
  const callback = await request('/api/zoom/oauth/callback?state=' + state + '&code=mock-code');
  assert.equal(callback.status, 302); assert.equal(callback.location, '/teacher.html?zoom=connected');
  assert.equal(calls.filter(url => url.endsWith('/users/me/zak')).length, 1, 'liên kết xác minh quyền bằng API ZAK chuyên dụng');
  assert.equal(tokenRequests[0].authorization, undefined);
  assert.equal(tokenRequests[0].fields.get('client_id'), 'mock-public');
  const verifier = tokenRequests[0].fields.get('code_verifier');
  assert.match(verifier, /^[A-Za-z0-9_-]{43,128}$/);
  assert.equal(crypto.createHash('sha256').update(verifier).digest('base64url'), params.get('code_challenge'));
  assert.equal((await request('/api/zoom/oauth/callback?state=' + state + '&code=mock-code')).status, 400, 'state chỉ dùng một lần');
  assert.equal((await request('/api/zoom/connection')).body.email, 'host@example.com');
  assert.equal(hostSetup(teacher, live.video).canStart, true, 'host liên kết đúng có thể mở trực tiếp trong web');
  assert.equal(hostSetup(teacher, { ...live.video, hostEmail: 'another@example.com' }).code, 'account', 'không nhận quyền chủ trì của người khác');
  let joined = await request('/api/zoom/join', 'teacher', { classId: c.id });
  assert.equal(joined.status, 200); assert.equal(joined.body.zak, 'mock-zak');
  assert.equal(calls.filter(url => url.endsWith('/users/me/zak')).length, 2, 'mở lớp lấy ZAK mới bằng cùng API đúng quyền');
  assert.equal(JSON.parse(Buffer.from(joined.body.signature.split('.')[1], 'base64url')).role, 1);
  store.data.zoomAccounts[teacher.id].expiresAt = 0;
  joined = await request('/api/zoom/join', 'teacher', { classId: c.id });
  assert.equal(joined.status, 200); assert.equal(calls.filter(url => url.includes('/oauth/token')).length, 2, 'token hết hạn phải refresh');
  assert.equal(tokenRequests[1].authorization, undefined); assert.equal(tokenRequests[1].fields.get('client_id'), 'mock-public');
  const studentJoined = await request('/api/zoom/join', 'student', { classId: c.id });
  assert.equal(studentJoined.status, 200); assert.equal(studentJoined.body.zak, undefined);
  live.video.hostMode = 'desktop';
  const legacyHost = await request('/api/zoom/join', 'teacher', { classId: c.id });
  assert.equal(legacyHost.status, 200);
  assert.equal(legacyHost.body.zak, 'mock-zak', 'chủ phòng đã liên kết lấy ZAK cả với cấu hình desktop cũ');
  assert.equal(legacyHost.body.hostInDesktop, false);
  assert.equal(JSON.parse(Buffer.from(legacyHost.body.signature.split('.')[1], 'base64url')).role, 1);
  const legacyStudent = await request('/api/zoom/join', 'student', { classId: c.id });
  assert.equal(legacyStudent.body.zak, undefined);
  assert.equal(JSON.parse(Buffer.from(legacyStudent.body.signature.split('.')[1], 'base64url')).role, 0);
  store.data.zoomAccounts[teacher.id].email = 'different@example.com';
  const differentOwner = await request('/api/zoom/join', 'teacher', { classId: c.id });
  assert.equal(differentOwner.body.zak, undefined, 'liên kết tài khoản khác không được nâng thành chủ trì');
  assert.equal(differentOwner.body.hostInDesktop, true);
  store.data.zoomAccounts[teacher.id].email = 'host@example.com';
  live.video.hostMode = 'sdk';
  const before = calls.length;
  const expired = await request('/api/zoom/connect', 'teacher', {}); sessionValid = false;
  assert.equal((await request('/api/zoom/oauth/callback?state=' + new URL(expired.body.url).searchParams.get('state') + '&code=mock-code')).status, 400);
  assert.equal(calls.length, before, 'phiên đăng nhập đã thu hồi không được trao đổi token');
  sessionValid = true;
  const local = await request('/api/zoom/connect', 'teacher', {}, 'http://localhost:3000');
  const localCallback = await request('/api/zoom/oauth/callback?state=' + new URL(local.body.url).searchParams.get('state') + '&code=mock-code');
  assert.equal(localCallback.location, 'http://localhost:3000/teacher.html?zoom=connected', 'quay lại origin cũ để giữ localStorage đăng nhập');
  store.data.settings.video.zoom.publicClientId = '';
  const missingPublic = await request('/api/zoom/connection');
  assert.equal(missingPublic.body.configured, true);
  assert.equal(missingPublic.body.oauthReady, false);
  assert.equal(missingPublic.body.pkceRequired, true);
  assert.equal(missingPublic.body.publicClientReady, false);
  assert.equal((await request('/api/zoom/connect', 'teacher', {})).status, 409, 'không khởi tạo OAuth HTTP thiếu PKCE');
  store.data.settings.video.zoom.redirectUri = 'https://school.example/api/zoom/oauth/callback';
  assert.equal((await request('/api/zoom/connection')).body.oauthReady, true);
  const confidential = await request('/api/zoom/connect', 'teacher', {});
  assert.equal(new URL(confidential.body.url).searchParams.get('client_id'), 'mock-client');
  assert.ok(!new URL(confidential.body.url).searchParams.has('code_challenge'));
  const end = await request('/api/zoom/oauth/callback?state=' + new URL(confidential.body.url).searchParams.get('state') + '&code=mock-code');
  assert.equal(end.location, '/teacher.html?zoom=connected');
  assert.equal(tokenRequests.at(-1).authorization, 'Basic ' + Buffer.from('mock-client:mock-secret').toString('base64'));
  for (const stage of ['token', 'profile', 'zak', 'network']) {
    failureStage = stage;
    const attempt = await request('/api/zoom/connect', 'teacher', {});
    const failed = await request('/api/zoom/oauth/callback?state=' + new URL(attempt.body.url).searchParams.get('state') + '&code=mock-code');
    assert.equal(failed.location, '/teacher.html?zoom=error');
    const detail = (await request('/api/zoom/connection')).body.lastError;
    assert.equal(detail.stage, stage === 'network' ? 'token' : stage);
    assert.equal(detail.code, stage === 'network' ? 'ECONNRESET' : '4711');
    if (stage !== 'network') assert.equal(detail.httpStatus, 401);
    for (const secret of ['mock-secret', 'mock-access', 'mock-refresh']) assert.ok(!JSON.stringify(detail).includes(secret));
    assert.equal((await request('/api/zoom/connection', 'student')).status, 403);
  }
  failureStage = '';
  const retry = await request('/api/zoom/connect', 'teacher', {});
  await request('/api/zoom/oauth/callback?state=' + new URL(retry.body.url).searchParams.get('state') + '&code=mock-code');
  assert.equal((await request('/api/zoom/connection')).body.lastError, null);
}
main().then(() => cleanup(0), error => { console.error(error); cleanup(1); });
function cleanup(code) { global.fetch = originalFetch; server?.close(); store.flush(); fs.rmSync(dir, { recursive: true, force: true }); process.exit(code); }
